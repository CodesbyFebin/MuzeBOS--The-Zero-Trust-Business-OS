import { signInOwner } from './browser-sign-in.mjs';
/** UI/API persistence checks. No model weights or paid provider calls are made. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
if (!process.env.TEST_JEV_DB) throw new Error('Run through npm run test:qualify-browser for a disposable fixture database');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:4100';
const browser = await chromium.launch({ executablePath: process.env.TEST_CHROMIUM_PATH || undefined, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });await signInOwner(page,base);
await page.addInitScript(() => { Object.defineProperty(navigator, 'gpu', { value: undefined, configurable: true }); });
const errors = []; page.on('pageerror', e => errors.push(e.message));
const api = async payload => page.request.post(base + '/api/inference', { headers: { origin: base, 'idempotency-key': crypto.randomUUID() }, data: payload });
try {
  await page.goto(base + '/workspace/brain/inference', { waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'Inference & agent workspace', exact: true }).waitFor();
  await page.getByText('WebGPU unavailable in this browser.', { exact: false }).waitFor();
  assert.equal(await page.locator('[data-workspace-entry]').count(), 18);
  await page.getByRole('button', { name: 'Load local Llama model', exact: true }).click();
  await page.locator('.mb-alert[role=alert]').filter({ hasText: 'WebGPU is unavailable' }).waitFor();
  const title = 'Browser inference review ' + Date.now();
  await page.getByLabel('Task title', { exact: true }).fill(title);
  await page.getByLabel('Task instructions', { exact: true }).fill('Write a short customer reply.');
  await page.getByRole('button', { name: 'Create task for review', exact: true }).click();
  const row = page.locator('.mb-booking-row').filter({ hasText: title }); await row.waitFor();
  assert.match(await row.innerText(), /clerk · small · browser · awaiting_approval/);
  await row.getByRole('button', { name: 'Review task', exact: true }).click();
  await page.getByRole('button', { name: 'Jev: approve exact task', exact: true }).click();
  await row.getByText(/queued/).waitFor();
  await page.reload({ waitUntil: 'networkidle' }); await row.waitFor(); assert.match(await row.innerText(), /queued/);
  const claim = await api({ action: 'claimBrowser', workerId: 'browser-fixture-harness' }); assert.equal(claim.status(), 200);
  const lease = (await claim.json()).result;
  const state = await (await page.request.get(base + '/api/inference')).json();
  assert.equal(JSON.stringify(state).includes(lease.token), false);
  const completed = await api({ action: 'completeBrowser', id: lease.task.id, token: lease.token, output: 'Fixture-only draft from verification harness; no live model used.' }); assert.equal(completed.status(), 200);
  await page.getByRole('button', { name: 'Refresh inference', exact: true }).click();
  await row.getByText(/completed/).waitFor(); await row.getByRole('button', { name: 'Review task', exact: true }).click();
  await page.getByRole('heading', { name: 'Model draft · requires human review', exact: true }).waitFor();
  await page.getByLabel('Subtasks JSON', { exact: true }).fill(JSON.stringify([{ title: 'Child review task', prompt: 'Draft a follow-up', kind: 'draft' }]));
  await page.getByRole('button', { name: 'Create subtasks for review', exact: true }).click();
  await page.locator('.mb-booking-row').filter({ hasText: 'Child review task' }).waitFor();
  await page.getByRole('navigation', { name: 'Inference views' }).getByRole('button', { name: 'Models', exact: true }).click();
  await page.getByRole('heading', { name: 'Model routes & configuration', exact: true }).waitFor();
  assert.match(await page.locator('.mb-console').innerText(), /Muse Wonder Full is not a generic API model/);
  await page.getByRole('navigation', { name: 'Inference views' }).getByRole('button', { name: 'Evidence', exact: true }).click();
  await page.getByText('No zkVM prover/verifier configured.', { exact: false }).waitFor();
  assert.match(await page.locator('.mb-console').innerText(), /inference.completed/);
  await page.route('**/api/inference', route => route.abort());
  await page.getByRole('button', { name: 'Refresh inference', exact: true }).click(); await page.locator('.mb-alert[role=alert]').waitFor();
  assert.match(await page.locator('.mb-console').innerText(), /inference.completed/); await page.unroute('**/api/inference');
  await page.setViewportSize({ width: 390, height: 844 }); await page.reload({ waitUntil: 'networkidle' });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Inference page overflows mobile viewport');
  // Isolated UI fixture for the new completed-server handoff; API authorization is tested separately.
  const serverTask = { ...state.tasks.find(t => t.id === lease.task.id), id: crypto.randomUUID(), state: 'completed', output: '{"tool":"reminders.create","args":{"title":"Synthetic server proposal"}}', outputHash: 'a'.repeat(64) };
  serverTask.payload = { ...serverTask.payload, title: 'Fixture server proposal', provider: 'baseten', model: 'meta-models/muse-spark-open-1026' };
  let handoffs = 0;
  await page.route('**/api/inference', async route => {
    if (route.request().method() === 'GET') return route.fulfill({ json: { ...state, tasks: [serverTask] } });
    assert.deepEqual(route.request().postDataJSON(), { action: 'proposeAction', id: serverTask.id });
    handoffs++;
    return route.fulfill({ json: { result: { id: 'ui-fixture-run', status: 'awaiting_approval' } } });
  });
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('.mb-booking-row').filter({ hasText: 'Fixture server proposal' }).getByRole('button', { name: 'Review task', exact: true }).click();
  await page.getByRole('button', { name: 'Send proposal to Jev', exact: true }).click();
  await page.getByText('Operation saved. Inference outputs remain drafts.', { exact: true }).waitFor();
  assert.equal(handoffs, 1);
  assert.equal(await page.getByRole('link', { name: 'Open Jev action approvals', exact: true }).getAttribute('href'), '/workspace/brain/runtime#jev');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Server proposal handoff overflows mobile viewport');
  await page.unroute('**/api/inference');
  // Real browser -> HTTP -> SQLite -> Jev -> reminder path, with only provider output fixture-injected.
  const fixture = JSON.parse(execFileSync(process.execPath, ['--import', 'tsx', 'scripts/metabos-jev-browser-fixture.ts', process.env.TEST_JEV_DB], { encoding: 'utf8' }));
  assert.equal(fixture.evidenceMode, 'fixture');
  await page.goto(base + '/workspace/brain/inference', { waitUntil: 'networkidle' });
  const fixtureRow = page.locator('.mb-booking-row').filter({ hasText: fixture.title });
  await fixtureRow.getByRole('button', { name: 'Review task', exact: true }).click();
  const handoffResponse = page.waitForResponse(r => r.url() === base + '/api/inference' && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Send proposal to Jev', exact: true }).click();
  const handoff = await handoffResponse; assert.equal(handoff.status(), 200);
  const actionRun = (await handoff.json()).result;
  assert.equal(actionRun.status, 'awaiting_approval');
  await page.getByRole('link', { name: 'Open Jev action approvals', exact: true }).click();
  await page.getByRole('region', { name: 'Jev approval queue', exact: true }).waitFor();
  const actionCard = page.locator(`[data-run="${actionRun.id}"]`);
  await actionCard.getByText(fixture.title, { exact: true }).waitFor();
  assert.match(await actionCard.innerText(), new RegExp(actionRun.payloadHash));
  assert.equal(await actionCard.getByRole('button', { name: 'Run approved write', exact: true }).count(), 0);
  await page.reload({ waitUntil: 'networkidle' }); // Hash link must survive reload.
  await actionCard.getByRole('button', { name: 'Approve this payload', exact: true }).click();
  await actionCard.getByRole('button', { name: 'Run approved write', exact: true }).click();
  await actionCard.locator('.mb-badge').filter({ hasText: 'succeeded' }).waitFor();
  await page.reload({ waitUntil: 'networkidle' });
  await actionCard.locator('.mb-badge').filter({ hasText: 'succeeded' }).waitFor();
  const overview = await (await page.request.get(base + '/api/mission-control')).json();
  assert.equal(overview.todo.filter(t => t.title.startsWith(fixture.title)).length, 1);
  assert.equal(overview.auditValid, true);
  const finalState = await (await page.request.get(base + '/api/workflow-runs')).json();
  const persisted = finalState.runs.find(r => r.id === actionRun.id);
  assert.equal(persisted.status, 'succeeded');
  assert.equal(persisted.steps[0].output.reminderIds.length, 1);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Jev queue overflows mobile viewport');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'PASS', checks: ['18 sidebar entries', 'WebGPU absence is explicit', 'persisted task creation', 'size and agent assignment', 'exact Jev approval', 'reload persistence', 'lease token hidden from snapshot', 'fixture-only completion contract', 'bounded child task review', 'provider readiness labels', 'no false zkVM proof', 'stale snapshot retained', 'mobile layout', 'fixture server proposal handoff', 'separate Jev approval link', 'real HTTP Jev queue navigation', 'approval before reminder execution', 'durable approved reminder', 'Jev hash link reload', 'no runtime errors'], limits: ['No physical WebGPU inference, paid provider or external agent runtime exercised'] }));
} finally { await browser.close(); }
