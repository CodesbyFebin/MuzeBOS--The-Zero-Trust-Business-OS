import { signInOwner } from './browser-sign-in.mjs';
/** Real browser → API → SQLite → UI verification. Use a disposable DB. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:4100';
const browser=await chromium.launch({executablePath:process.env.TEST_CHROMIUM_PATH||undefined,headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});await signInOwner(page,base);
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const suffix=Date.now().toString();
const clickTab=async name=>page.getByRole('navigation',{name:'Business views'}).getByRole('button',{name,exact:true}).click();
try {
 await page.goto(base+'/business',{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:'Business intelligence'}).waitFor();
 await page.getByText('Opening your local workspace…').waitFor({state:'hidden'});
 await clickTab('customers');
 await page.getByLabel('Customer name',{exact:true}).fill(`Browser merchant ${suffix}`);
 await page.getByLabel('Email (optional)').fill('test@example.com');
 await page.getByRole('button',{name:'Save customer',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Record saved.'}).waitFor();
 await clickTab('inventory');
 await page.getByLabel('Product name',{exact:true}).fill(`Browser coffee ${suffix}`);
 await page.getByLabel('SKU',{exact:true}).fill(`BR-${suffix}`);
 await page.getByLabel('Unit price (INR)').fill('199.99');
 await page.getByLabel('Tax rate (%)').fill('18');
 await page.getByLabel('Opening stock').fill('5');
 await page.getByRole('button',{name:'Save product',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Record saved.'}).waitFor();
 await clickTab('orders');
 const customerOption=page.getByLabel('Customer',{exact:true}).getByRole('option',{name:`Browser merchant ${suffix}`,exact:true});
 await page.getByLabel('Customer',{exact:true}).selectOption(await customerOption.getAttribute('value'));
 const productOption=page.getByLabel('Product',{exact:true}).getByRole('option').filter({hasText:`BR-${suffix}`});
 await page.getByLabel('Product',{exact:true}).selectOption(await productOption.getAttribute('value'));
 await page.getByLabel('Quantity',{exact:true}).fill('2');
 await page.getByRole('button',{name:'Create draft for review'}).click();
 await page.getByRole('status').filter({hasText:'Draft ready for review'}).waitFor();
 const draft=page.locator('.mb-order').filter({hasText:`Browser merchant ${suffix}`});
 assert.match(await draft.innerText(),/471\.98/);
 await draft.getByRole('button',{name:'Approve & issue'}).click();
 await page.getByRole('status').filter({hasText:'Invoice issued and inventory updated'}).waitFor();
 await clickTab('invoices');
 const invoice=page.locator('.mb-order').filter({hasText:`Browser merchant ${suffix}`});
 assert.match(await invoice.innerText(),/pending/);
 await invoice.getByLabel('Manual settlement reference').fill(`TEST-ONLY-${suffix}`);
 await invoice.getByRole('button',{name:'Record manual reconciliation'}).click();
 await page.getByRole('status').filter({hasText:'Recorded as manually reconciled'}).waitFor();
 await page.reload({waitUntil:'networkidle'});
 await clickTab('inventory');
 const product=page.locator('.mb-row').filter({hasText:`BR-${suffix}`});
 assert.match(await product.innerText(),/3 IN STOCK/);
 await clickTab('evidence');
 await page.getByText('HASH CHAIN VERIFIED',{exact:true}).waitFor();
 assert.match(await page.locator('.mb-panel').innerText(),/invoice\.issued/);
 await clickTab('overview');
 await page.getByRole('button',{name:`Customer: Browser merchant ${suffix}`}).click();
 assert.match(await page.locator('.mb-node-detail').innerText(),/test@example.com/);
 if(process.env.TEST_SCREENSHOT)await page.screenshot({path:process.env.TEST_SCREENSHOT,fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.reload({waitUntil:'networkidle'});
 await page.getByRole('navigation',{name:'Business views'}).waitFor();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'Mobile viewport overflows horizontally');
 assert.deepEqual(errors,[],'Browser runtime errors');
 console.log(JSON.stringify({result:'PASS',checks:['customer creation','product creation','exact draft total','approval and issuance','pending payment','explicit manual reconciliation','stock persistence after reload','audit verification','graph selection','mobile layout','no browser runtime errors']},null,2));
} catch(error) { console.error('Visible error:',await page.locator('[role=alert]').allTextContents()); throw error; } finally {await browser.close();}
